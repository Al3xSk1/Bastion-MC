//! TLS policy.
//!
//! * TLS 1.3 only. rustls is compiled without its `tls12` feature, so there is no downgrade
//!   path to remove at runtime; the protocol list below is belt and braces.
//! * Trust anchors come from the distribution CA bundle at a fixed, root-owned path. The
//!   `SSL_CERT_FILE` / `SSL_CERT_DIR` environment overrides are deliberately not honoured.
//! * Optional SPKI pins. A pin is checked against the chain that actually *validated*, not the
//!   list of certificates the server chose to send: a MITM holding a mis-issued certificate
//!   could otherwise satisfy an intermediate pin by attaching the pinned certificate as an
//!   unused extra. Pins can only ever restrict; unpinned hosts get stock WebPKI validation.

use std::{collections::BTreeMap, path::Path, sync::Arc};

use rustls::{
    CertificateError, ClientConfig, DigitallySignedStruct, RootCertStore, SignatureScheme,
    client::{
        WebPkiServerVerifier,
        danger::{HandshakeSignatureValid, ServerCertVerified, ServerCertVerifier},
    },
    crypto::CryptoProvider,
    pki_types::{CertificateDer, ServerName, UnixTime, pem::PemObject},
};

use crate::{
    error::{Error, Result},
    util::{self, HashAlg},
};

/// Arch Linux: provided by `ca-certificates-utils`, regenerated by `update-ca-trust`.
pub const SYSTEM_CA_BUNDLE: &str = "/etc/ssl/certs/ca-certificates.crt";

pub type Pin = [u8; 32];

/// Keys that are stable in the chain every Microsoft/Mojang endpoint presents
/// (leaf → rotating "Microsoft TLS G2 RSA CA OCSP nn" → Microsoft TLS RSA Root G2 → DigiCert
/// Global Root G2), plus the roots Microsoft documents as successors for its services.
/// Leaf and issuing-CA keys rotate every few months and are deliberately not pinned.
///
/// Effect: for these hosts the set of acceptable trust anchors shrinks from the whole system
/// store (~120 CAs) to this list. If Microsoft ever moves to a root outside it, connections
/// fail closed until the list is updated or `tls.builtin_pins = false` is set.
pub const MICROSOFT_PINS: &[(&str, &str)] = &[
    ("DigiCert Global Root G2", "i7WTqTvh0OioIruIfFR4kMPnBqrS2rdiVPl/s2uC/CY="),
    ("Microsoft TLS RSA Root G2", "SwPJlmyGOywAipWl7ZJUBwRIx7IZ0oMQL2psW26OKs0="),
    ("Microsoft RSA Root Certificate Authority 2017", "svcpi1K/LDysTd/nLeTWgqxYlXWVmC8rYjAa9ZfGmcU="),
    ("Microsoft ECC Root Certificate Authority 2017", "NfU84SZGEeAzQP434ex9TMmGxWE9ynD9BKpEVF8tryg="),
    ("DigiCert Global Root G3", "uUwZgwDOxcBXrQcntwu+kYFpkiVkOaezL0WYEZ3anJc="),
    ("DigiCert TLS RSA4096 Root G5", "ape1HIIZ6T5d7GS61YBs3rD4NVvkfnVwELcCRW4Bqv0="),
    ("DigiCert TLS ECC P384 Root G5", "oC+voZLIy4HLE0FVT5wFtxzKKokLDRKY1oNkfJYe+98="),
];

/// Host patterns the built-in pins apply to: everything the launcher (and the credential
/// broker on the game's behalf) talks to that is operated by Microsoft/Mojang.
pub const MICROSOFT_HOSTS: &[&str] = &[
    ".mojang.com",
    ".minecraft.net",
    ".minecraftservices.com",
    ".xboxlive.com",
    "login.microsoftonline.com",
    // Realms from 1.21.8 on (the broker reaches it on the game's behalf, `realms`). Its chain
    // ends in Microsoft TLS RSA Root G2 / DigiCert Global Root G2 (seen 2026-11-14).
    ".realms.minecraft-services.net",
];

/// Parse `sha256/<base64>` (the HPKP notation: SHA-256 over the DER SubjectPublicKeyInfo).
pub fn parse_pin(s: &str) -> Result<Pin> {
    let b64 = s
        .strip_prefix("sha256/")
        .ok_or_else(|| Error::Config(format!("TLS pin {s:?} must look like sha256/<base64>")))?;
    util::b64_decode(b64)
        .ok()
        .and_then(|v| Pin::try_from(v).ok())
        .ok_or_else(|| Error::Config(format!("TLS pin {s:?} is not 32 bytes of base64")))
}

#[derive(Debug, Clone, Default)]
pub struct PinSet {
    exact: BTreeMap<String, Vec<Pin>>,
    /// (".example.com", pins), longest suffix first.
    suffix: Vec<(String, Vec<Pin>)>,
}

impl PinSet {
    /// How many host patterns (exact names and suffixes) carry pins.
    pub fn host_count(&self) -> usize {
        self.exact.len() + self.suffix.len()
    }

    /// User pins from the configuration, plus the built-in Microsoft/Mojang set unless
    /// disabled. A user entry for the same pattern replaces the built-in one.
    pub fn from_config(map: &BTreeMap<String, Vec<String>>, builtin: bool) -> Result<Self> {
        let mut merged: BTreeMap<String, Vec<String>> = BTreeMap::new();
        if builtin {
            let pins: Vec<String> = MICROSOFT_PINS.iter().map(|(_, p)| format!("sha256/{p}")).collect();
            for host in MICROSOFT_HOSTS {
                merged.insert(host.to_string(), pins.clone());
            }
        }
        for (host, pins) in map {
            merged.insert(host.to_ascii_lowercase(), pins.clone());
        }
        Self::parse(&merged)
    }

    fn parse(map: &BTreeMap<String, Vec<String>>) -> Result<Self> {
        let mut set = PinSet::default();
        for (host, pins) in map {
            let pins = pins.iter().map(|p| parse_pin(p)).collect::<Result<Vec<_>>>()?;
            if pins.is_empty() {
                return Err(Error::Config(format!("tls.pins.{host:?} is empty; remove it or add a pin")));
            }
            let host = host.to_ascii_lowercase();
            if host.starts_with('.') {
                set.suffix.push((host, pins));
            } else {
                set.exact.insert(host, pins);
            }
        }
        set.suffix.sort_by_key(|(s, _)| std::cmp::Reverse(s.len()));
        Ok(set)
    }

    pub fn for_host(&self, host: &str) -> Option<&[Pin]> {
        let host = host.to_ascii_lowercase();
        if let Some(p) = self.exact.get(&host) {
            return Some(p);
        }
        self.suffix.iter().find(|(s, _)| host.ends_with(s.as_str())).map(|(_, p)| p.as_slice())
    }

    pub fn is_empty(&self) -> bool {
        self.exact.is_empty() && self.suffix.is_empty()
    }
}

/// The certificates of the distribution trust store. The file must be root-owned and not
/// writable by others.
pub fn load_system_certificates() -> Result<Vec<CertificateDer<'static>>> {
    let bundle = util::require_root_owned(Path::new(SYSTEM_CA_BUNDLE))?;
    CertificateDer::pem_file_iter(&bundle)
        .map_err(|e| Error::Tls(format!("cannot read {}: {e}", bundle.display())))?
        .collect::<std::result::Result<_, _>>()
        .map_err(|e| Error::Tls(format!("cannot parse {}: {e}", bundle.display())))
}

/// Load the distribution trust store as trust anchors for the launcher's own connections.
pub fn load_system_roots() -> Result<RootCertStore> {
    let mut roots = RootCertStore::empty();
    let (added, _ignored) = roots.add_parsable_certificates(load_system_certificates()?);
    if added == 0 {
        return Err(Error::Tls(format!("{SYSTEM_CA_BUNDLE} contains no usable CA certificates")));
    }
    Ok(roots)
}

pub fn provider() -> Arc<CryptoProvider> {
    Arc::new(rustls::crypto::aws_lc_rs::default_provider())
}

/// Build the one client configuration every launcher connection uses.
pub fn client_config(roots: RootCertStore, pins: PinSet) -> Result<Arc<ClientConfig>> {
    let provider = provider();
    let roots = Arc::new(roots);
    let inner = WebPkiServerVerifier::builder_with_provider(roots.clone(), provider.clone())
        .build()
        .map_err(|e| Error::Tls(format!("cannot build certificate verifier: {e}")))?;
    let verifier = Arc::new(PinningVerifier { inner, roots, provider: provider.clone(), pins });

    let mut config = ClientConfig::builder_with_provider(provider)
        .with_protocol_versions(&[&rustls::version::TLS13])
        .map_err(|e| Error::Tls(format!("TLS 1.3 unavailable: {e}")))?
        .dangerous() // "dangerous" = custom verifier; ours wraps the stock one and only adds checks
        .with_custom_certificate_verifier(verifier)
        .with_no_client_auth();
    config.alpn_protocols = vec![b"http/1.1".to_vec()];
    config.enable_early_data = false; // 0-RTT data is replayable
    config.enable_sni = true;
    Ok(Arc::new(config))
}

#[derive(Debug)]
struct PinningVerifier {
    inner: Arc<WebPkiServerVerifier>,
    roots: Arc<RootCertStore>,
    provider: Arc<CryptoProvider>,
    pins: PinSet,
}

fn spki_hash(spki: &[u8]) -> Pin {
    Pin::try_from(util::hash_bytes(HashAlg::Sha256, spki)).expect("SHA-256 is 32 bytes")
}

impl PinningVerifier {
    /// Succeeds iff some valid path from `end_entity` to a trust anchor contains a pinned key.
    fn check_pins(
        &self,
        end_entity: &CertificateDer<'_>,
        intermediates: &[CertificateDer<'_>],
        now: UnixTime,
        pins: &[Pin],
    ) -> std::result::Result<(), rustls::Error> {
        let mismatch = || rustls::Error::InvalidCertificate(CertificateError::ApplicationVerificationFailure);
        let cert = webpki::EndEntityCert::try_from(end_entity).map_err(|_| mismatch())?;
        let pinned = |hash: Pin| pins.iter().any(|p| util::ct_eq(p, &hash));
        // Rejecting a path here makes path building continue with the next candidate, so a
        // cross-signed chain is accepted as long as one valid path satisfies the pin.
        let path_ok = |path: &webpki::VerifiedPath<'_>| -> std::result::Result<(), webpki::Error> {
            let leaf = pinned(spki_hash(path.end_entity().subject_public_key_info().as_ref()));
            let mid = path.intermediate_certificates().any(|c| pinned(spki_hash(c.subject_public_key_info().as_ref())));
            let root = pinned(spki_hash(webpki::spki_for_anchor(path.anchor()).as_ref()));
            if leaf || mid || root { Ok(()) } else { Err(webpki::Error::UnknownIssuer) }
        };
        cert.verify_for_usage(
            self.provider.signature_verification_algorithms.all,
            &self.roots.roots,
            intermediates,
            now,
            webpki::KeyUsage::server_auth(),
            None,
            Some(&path_ok),
        )
        .map(|_| ())
        .map_err(|_| mismatch())
    }
}

impl ServerCertVerifier for PinningVerifier {
    fn verify_server_cert(
        &self,
        end_entity: &CertificateDer<'_>,
        intermediates: &[CertificateDer<'_>],
        server_name: &ServerName<'_>,
        ocsp_response: &[u8],
        now: UnixTime,
    ) -> std::result::Result<ServerCertVerified, rustls::Error> {
        // 1. Stock validation: chain, validity period, EKU, name. Untouched.
        let verified = self.inner.verify_server_cert(end_entity, intermediates, server_name, ocsp_response, now)?;
        // 2. Additional restriction for pinned hosts.
        if let ServerName::DnsName(name) = server_name
            && let Some(pins) = self.pins.for_host(name.as_ref())
        {
            self.check_pins(end_entity, intermediates, now, pins)?;
        }
        Ok(verified)
    }

    fn verify_tls12_signature(
        &self,
        message: &[u8],
        cert: &CertificateDer<'_>,
        dss: &DigitallySignedStruct,
    ) -> std::result::Result<HandshakeSignatureValid, rustls::Error> {
        self.inner.verify_tls12_signature(message, cert, dss)
    }

    fn verify_tls13_signature(
        &self,
        message: &[u8],
        cert: &CertificateDer<'_>,
        dss: &DigitallySignedStruct,
    ) -> std::result::Result<HandshakeSignatureValid, rustls::Error> {
        self.inner.verify_tls13_signature(message, cert, dss)
    }

    fn supported_verify_schemes(&self) -> Vec<SignatureScheme> {
        self.inner.supported_verify_schemes()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pin_syntax() {
        let good = format!("sha256/{}", util::b64_encode(&[7u8; 32]));
        assert_eq!(parse_pin(&good).unwrap(), [7u8; 32]);
        assert!(parse_pin("sha1/AAAA").is_err());
        assert!(parse_pin("sha256/AAAA").is_err());
        assert!(parse_pin(&util::b64_encode(&[7u8; 32])).is_err());
    }

    #[test]
    fn pin_lookup_prefers_exact_then_longest_suffix() {
        let pin = |b: u8| vec![format!("sha256/{}", util::b64_encode(&[b; 32]))];
        let mut m = BTreeMap::new();
        m.insert("api.example.com".to_string(), pin(1));
        m.insert(".example.com".to_string(), pin(2));
        m.insert(".cdn.example.com".to_string(), pin(3));
        let set = PinSet::from_config(&m, false).unwrap();
        assert_eq!(set.for_host("API.example.com").unwrap()[0], [1; 32]);
        assert_eq!(set.for_host("x.example.com").unwrap()[0], [2; 32]);
        assert_eq!(set.for_host("a.cdn.example.com").unwrap()[0], [3; 32]);
        assert!(set.for_host("example.org").is_none());
        // ".example.com" must not match "evilexample.com"
        assert!(set.for_host("evilexample.com").is_none());
    }

    #[test]
    fn builtin_pins_cover_microsoft_hosts_and_match_the_system_store() {
        let set = PinSet::from_config(&BTreeMap::new(), true).unwrap();
        for host in [
            "api.minecraftservices.com",
            "sessionserver.mojang.com",
            "libraries.minecraft.net",
            "user.auth.xboxlive.com",
            "login.microsoftonline.com",
        ] {
            assert_eq!(set.for_host(host).map(<[Pin]>::len), Some(MICROSOFT_PINS.len()), "{host}");
        }
        for host in ["maven.fabricmc.net", "example.com", "evilmojang.com", "login.microsoftonline.com.evil.example"] {
            assert!(set.for_host(host).is_none(), "{host} must not be pinned");
        }
        assert!(PinSet::from_config(&BTreeMap::new(), false).unwrap().is_empty());
        // A user entry replaces the built-in one for that pattern only.
        let mut m = BTreeMap::new();
        m.insert(".mojang.com".to_string(), vec![format!("sha256/{}", util::b64_encode(&[9u8; 32]))]);
        let set = PinSet::from_config(&m, true).unwrap();
        assert_eq!(set.for_host("api.mojang.com").unwrap(), &[[9u8; 32]]);
        assert_eq!(set.for_host("a.minecraft.net").unwrap().len(), MICROSOFT_PINS.len());

        // The hard-coded values are real: the root every endpoint chains to today must be in
        // the distribution trust store under exactly this key.
        let roots = load_system_roots().unwrap();
        let system: Vec<Pin> = roots.roots.iter().map(|a| spki_hash(webpki::spki_for_anchor(a).as_ref())).collect();
        let pin_of = |name: &str| {
            parse_pin(&format!("sha256/{}", MICROSOFT_PINS.iter().find(|(n, _)| *n == name).unwrap().1)).unwrap()
        };
        assert!(system.contains(&pin_of("DigiCert Global Root G2")), "primary pin does not match the system store");
        let present = MICROSOFT_PINS.iter().filter(|(n, _)| system.contains(&pin_of(n))).count();
        assert!(present >= 4, "only {present} built-in pins correspond to system trust anchors");
    }

    #[test]
    fn system_roots_load() {
        let roots = load_system_roots().expect("system CA bundle");
        assert!(roots.len() > 20);
    }
}
